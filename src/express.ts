/**
 * Every method name Express can register a route under.
 *
 * Taken from Node's own list — which is where Express's `methods` dependency
 * gets it too — rather than from a hand-written set of the seven anybody
 * remembers. A hand-written set is a hole shaped like `router.trace(...)`.
 */
const ROUTE_METHODS: readonly string[] = [
  ...new Set([...METHODS.map((m) => m.toLowerCase()), "delete", "all"]),
];

const PLEASE_DECLARE = [
  "Every route must say what it needs, at the point it is registered:",
  "",
  "    auth.allowPublic()                 — anyone, including an anonymous visitor",
  "    auth.requireSession()              — any verified session",
  '    auth.requireScope("fleet:control") — a session carrying that scope',
  "",
  "If this handler is middleware rather than a route — a body parser, CORS, a",
  "logger — wrap it: passthrough(handler, \"why it never answers\").",
].join("\n");

const flattenHandlers = (values: readonly unknown[]): unknown[] => {
  const out: unknown[] = [];
  for (const value of values) {
    if (Array.isArray(value)) out.push(...flattenHandlers(value));
    else out.push(value);
  }
  return out;
};

/** The leading path/pattern arguments Express accepts, which are not handlers. */
const isPathArgument = (value: unknown): boolean =>
  typeof value === "string" ||
  value instanceof RegExp ||
  (Array.isArray(value) && value.every(isPathArgument));

const describePath = (value: unknown): string =>
  isPathArgument(value) ? String(value) : "<no path>";

/**
 * Refuse, at startup, to register a route with no declaration.
 *
 * `label` is the method the call came in on, used only in the message. The
 * throw is deliberately an `Error` at require/boot time: a service that cannot
 * say what one of its routes needs must not start, because the alternative is
 * that it starts and serves it.
 */
const assertRouteDeclared = (
  label: string,
  args: readonly unknown[],
  name: string
): void => {
  const handlers = flattenHandlers(args).filter((a) => !isPathArgument(a));
  const declared = handlers.some(
    (h) =>
      typeof h === "function" && (declarations.has(h) || guards.has(h))
  );
  if (declared) return;

  throw new Error(
    `${name}.${label}(${describePath(args[0])}) was registered without an authorization declaration.\n\n` +
      PLEASE_DECLARE
  );
};

/**
 * The same, for `use()`. A `use` may legitimately mount things that are not
 * routes, so it accepts more: a declaration, a router-level guard, another
 * secured router, an explicitly vouched-for passthrough, or an error handler
 * (arity 4 — Express only ever calls it with an error in hand, so it cannot
 * be the thing that serves an undeclared route).
 */
const assertUseSafe = (args: readonly unknown[], name: string): void => {
  const mounted = flattenHandlers(args).filter((a) => !isPathArgument(a));
  for (const item of mounted) {
    if (typeof item === "function") {
      if (declarations.has(item)) continue;
      if (guards.has(item)) continue;
      if (passthroughs.has(item)) continue;
      if (securedTargets.has(item)) continue; // an express.Router() is a function
      if (item.length >= 4) continue; // an error handler
    } else if (typeof item === "object" && item !== null && securedTargets.has(item)) {
      continue;
    }

    throw new Error(
      `${name}.use(${describePath(args[0])}) was given a handler that is neither a declaration nor a vouched-for middleware.\n\n` +
        PLEASE_DECLARE +
        "\n\nA nested router is fine too, as long as it is itself secured():\n" +
        "\n    api.use(\"/ships\", secured(express.Router()));\n"
    );
  }
};

/**
 * Make an Express router or app refuse, **at registration time**, to register
 * a handler that carries no authorization declaration.
 *
 * ```ts
 * const api = secured(express.Router());
 * api.get("/ships", auth.requireSession(), listShips);   // fine
 * api.get("/ships", listShips);                          // throws at startup
 * ```
 *
 * This is the backstop that cannot be forgotten, and it is a *startup* failure
 * rather than a per-request one: an undeclared route does not exist, instead
 * of existing and being caught the first time somebody asks for it. A
 * per-request default-deny can only ever be as good as the code path that
 * notices; this one is as good as the process starting.
 *
 * The target is patched in place and returned, so `app.use("/api", api)`,
 * nesting and everything else about it are unchanged. Calling it twice on the
 * same target does nothing the second time.
 *
 * **What it does not cover**, stated because a fence whose gaps are unknown is
 * worse than no fence:
 *
 * - handlers registered on the *app* rather than on a secured router;
 * - handlers registered through a reference to the raw router captured before
 *   `secured()` was called;
 * - anything mounted *before* the secured router in the middleware chain,
 *   which answers without ever reaching it;
 * - what a `passthrough()` actually does, which is the caller's word.
 */
export function secured<T extends object>(target: T): T {
  if (securedTargets.has(target)) return target;
  securedTargets.add(target);

  const record = target as unknown as Record<string, unknown>;
  const name =
    typeof record["name"] === "string" && record["name"].length > 0
      ? (record["name"] as string)
      : "router";

  for (const method of ROUTE_METHODS) {
    const original = record[method];
    if (typeof original !== "function") continue;
    const call = original.bind(target) as (...args: unknown[]) => unknown;
    record[method] = (...args: unknown[]): unknown => {
      // `app.get("view engine")` is Express's settings GETTER, not a route.
      // One string argument and nothing else is unambiguously that: a route
      // with a path and no handler at all is not a route either.
      if (method === "get" && args.length === 1 && typeof args[0] === "string") {
        return call(...args);
      }
      assertRouteDeclared(method, args, name);
      return call(...args);
    };
  }

  const originalUse = record["use"];
  if (typeof originalUse === "function") {
    const call = originalUse.bind(target) as (...args: unknown[]) => unknown;
    record["use"] = (...args: unknown[]): unknown => {
      assertUseSafe(args, name);
      return call(...args);
    };
  }

  // `router.route("/x").get(handler)` registers a route without going through
  // `router.get`, so the returned IRoute is secured too — otherwise it is a
  // hole in the shape of a chaining style somebody prefers.
  const originalRoute = record["route"];
  if (typeof originalRoute === "function") {
    const call = originalRoute.bind(target) as (...args: unknown[]) => unknown;
    record["route"] = (...args: unknown[]): unknown => {
      const route = call(...args);
      return typeof route === "object" && route !== null
        ? secured(route as object)
        : route;
    };
  }

  return target;
}

export interface ExpressAuth {
  /**
   * Declare what a route needs, and enforce it. Attach it to the route:
   *
   * ```ts
   * api.post("/ships/:id/navigate", auth.requires("fleet:control"), navigate);
   * ```
   *
   * Express's own matcher binds this to the same route it binds the handler
   * to, so a mount prefix, a trailing slash, a case-variant path and a
   * parameter all resolve exactly as the route does — and a `HEAD` reaches the
   * `GET` route's declaration because Express dispatches it to that route.
   */
  requires(requires: RouteRequirement): HandlerLike;
  /** `requires(scope)`, spelled the way the services that exist today spell it. */
  requireScope(scope: string): HandlerLike;
  /** Any verified session, carrying any scopes at all, including none. */
  requireSession(): HandlerLike;
  /**
   * Declare a route **public**: an anonymous caller proceeds as a visitor on a
   * safe method, and a mutating method answers `500`, because a mutation that
   * needs no credential is a defect rather than a policy.
   *
   * This is the only way a route is public. A declaration nobody wrote is not
   * a public route, it is an undeclared one.
   */
  allowPublic(): HandlerLike;
  /**
   * Router-level middleware, for routes that cannot carry a declaration —
   * generated routers, chiefly. Mount once with `router.use(auth.guard(...))`.
   *
   * `resolve` is a fixed requirement or a function of the request. Returning
   * `undefined`, or throwing, means **undeclared**: `500` on every method,
   * before the header is read. There is no fallback to `"none"`.
   *
   * The request handed to `resolve` carries `method`, `path`, `baseUrl`,
   * `originalUrl` and `header()`. It does **not** carry a matched `route`: a
   * `use`-mounted middleware runs before any route layer matches, which is
   * precisely why a resolver must not key on a path it reconstructs itself.
   * Key on the method, or use per-route declarations.
   *
   * On a `HEAD`, `resolve` is called with `method` reading `"GET"`, because
   * `HEAD /x` is the same route as `GET /x` and Express dispatches it to that
   * handler. The real `req.method` is not touched.
   */
  guard(resolve: RouteRequirement | RequirementResolver): HandlerLike;
}

/** Writes a rejection in the family's `{"error":{"message":…}}` envelope. */
const sendRejection = (
  res: ResponseLike,
  status: number,
  message: string
): void => {
  res.status(status).json({ error: { message } });
};

const apply = (res: ResponseLike, decision: Decision, next: NextLike): void => {
  if (decision.outcome === "reject") {
    sendRejection(res, decision.status, decision.message);
    return;
  }
  res.locals[LOCALS_IDENTITY] = decision.identity;
  res.locals[LOCALS_ACTOR] = decision.identity?.sub ?? null;
  next();
};

/**
 * The same request, reading `GET` as its method.
 *
 * Only for handing to a {@link RequirementResolver}: `HEAD /x` is routed to
 * the `GET /x` handler by Express, so what `GET /x` declared is what governs
 * it. Nothing is mutated — the real `req.method` the handlers and the policy
 * see is untouched, so a `HEAD` is still answered as a `HEAD`.
 */
const asGet = (req: RequestLike): RequestLike =>
  new Proxy(req, {
    get(target, property) {
      if (property === "method") return "GET";
      const value = Reflect.get(target, property, target) as unknown;
      // Bound to the real request: Express's `path`/`header` read internals
      // that a proxy receiver would not satisfy.
      return typeof value === "function" ? value.bind(target) : value;
    },
  }) as RequestLike;

export function createExpressAuth(
  source: IntrospectionConfig | Introspector | Authorizer
): ExpressAuth {
  const authorizer: Authorizer =
    "authorize" in source ? source : createAuthorizer(source);

  const handlerFor = (resolve: RequirementResolver): HandlerLike => {
    return (req, res, next) => {
      let requires: RouteRequirement | undefined;
      try {
        requires =
          req.method.toUpperCase() === "HEAD" ? resolve(asGet(req)) : resolve(req);
      } catch {
        requires = undefined;
      }

      if (requires === undefined) {
        // Undeclared. A resolver that threw has told us nothing about this
        // route; a resolver that returned `undefined` has told us it could
        // not find it. Both are the same class of defect — ours — and both
        // fail closed on EVERY method, safe ones included.
        //
        // The alternative, and the bug this replaced: falling back to `"none"`
        // makes a miss indistinguishable from a route that declared itself
        // public, so after the safe methods were exempted from default-deny a
        // missed `GET`, `HEAD` or `OPTIONS` was served anonymously and in
        // silence. `"session"` would be no better — it serves the route to
        // anyone holding any token at all. Neither is a thing to guess.
        res.locals[LOCALS_REQUIRES] = null;
        sendRejection(res, 500, MESSAGES.undeclaredRoute);
        return;
      }
      res.locals[LOCALS_REQUIRES] = requires;

      authorizer
        .authorize({
          method: req.method,
          requires,
          // A repeated header arrives joined; `bearerFrom` reads that as no
          // credential rather than picking one of the two.
          authorization: headerValue(req, "Authorization"),
        })
        .then((decision) => apply(res, decision, next))
        // The authorizer is written not to reject; if a host's injected
        // introspector does, the request must still fail closed rather than
        // hand Express an unhandled promise. `next(err)` and not `next()`:
        // passing no error would run the handler the guard just failed to
        // authorize.
        .catch(() => next(new Error("introspection failed")));
    };
  };

  /** A handler that declares `requires`, tagged so `secured()` can see it. */
  const declaring = (requires: RouteRequirement): HandlerLike => {
    const handler = handlerFor(() => requires);
    declarations.set(handler, requires);
    return handler;
  };

  return {
    requires: declaring,
    requireScope: declaring,
    requireSession: () => declaring("session"),
    allowPublic: () => declaring("none"),
    guard: (resolve) => {
      const handler = handlerFor(
        typeof resolve === "function" ? resolve : () => resolve
      );
      guards.add(handler);
      return handler;
    },
  };
}

/** One header as a single string, or null. An array is joined as Node joins. */
const headerValue = (req: RequestLike, name: string): string | null => {
  const value = req.header(name);
  if (value === undefined) return null;
  return Array.isArray(value) ? value.join(", ") : value;
};
