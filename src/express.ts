/*
 * What a handler is, recorded outside the handler.
 *
 * WeakMaps rather than a property on the function, so nothing this package is
 * handed is mutated — a frozen middleware, or one shared with another library,
 * is none of our business. These are module-scoped, which assumes one copy of
 * this package per process. That is true for the three consumers (each
 * installs one tarball) and, if it ever stopped being true, `secured()` would
 * not recognise the other copy's declarations and would refuse to start with
 * the message below — the loudest possible way for that to surface.
 */

/** Handlers that carry a route declaration, and what they declare. */
const declarations = new WeakMap<object, RouteRequirement>();
/** Router-level guards: a blanket declaration for everything behind them. */
const guards = new WeakSet<object>();
/** Handlers a caller has explicitly vouched for as not being a route. */
const passthroughs = new WeakSet<object>();
/** Routers and apps already wrapped by {@link secured}. */
const securedTargets = new WeakSet<object>();

/** What a declared handler declares, or undefined if it declares nothing. */
export const declarationOf = (
  handler: unknown
): RouteRequirement | undefined =>
  typeof handler === "function" ? declarations.get(handler) : undefined;

/**
 * Vouch for a handler that is **not a route**: a body parser, a CORS
 * middleware, a logger — anything that will call `next()` rather than answer.
 *
 * {@link secured} refuses a `use()` of an undeclared handler, because from the
 * outside a middleware and a route are the same shape and it cannot tell which
 * one will answer. This is the explicit way to say which it is, and `why` is
 * required so the escape hatch reads as a decision in the diff rather than as
 * a cast.
 *
 * ```ts
 * api.use(passthrough(express.json(), "parses bodies; never answers"));
 * ```
 *
 * The handler is returned unchanged, so arity — which is how Express tells an
 * error handler from an ordinary one — is preserved exactly.
 */
export function passthrough<H>(handler: H, why: string): H {
  if (typeof handler !== "function") {
    throw new TypeError("passthrough() takes a middleware function");
  }
  if (typeof why !== "string" || why.trim().length === 0) {
    throw new TypeError(
      "passthrough() requires a reason: say why this handler is not a route that needs a declaration"
    );
  }
  passthroughs.add(handler);
  return handler;
}

