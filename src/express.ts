/**
 * @file Express 4 adapter.
 *
 * Express is a **development dependency of this repository only**: nothing
 * here imports it at runtime *or at type level*. The interfaces below are the
 * minimum shape the adapter touches, declared locally, so the shipped `.d.ts`
 * mentions no package a consumer might not have — a consumer with
 * `skipLibCheck: false` and no `@types/express` typechecks against this file,
 * which is the claim CI proves with two separate tarball probes. Real Express
 * `Request`/`Response`/`RequestHandler` values are structurally assignable in
 * both directions, so nothing here needs a cast.
 *
 * ## The rule this file exists to enforce
 *
 * **A route with no declaration is never served, for any method.** Not for
 * `GET`, not for `HEAD`, not for `OPTIONS`. "Public" is a thing a route says
 * out loud — {@link ExpressAuth.allowPublic} — and never a thing that happens
 * because a lookup missed.
 *
 * The previous design got this wrong in a way worth recording, because the
 * shape is common. It offered a router-level `guard(resolve)` whose resolver
 * was handed `req.method` and `req.path`, and the README taught the resolver
 * body `table[`${method} ${path}`] ?? "none"`. Three things were then true at
 * once:
 *
 * - a **miss** was indistinguishable from a declaration of `"none"`, so after
 *   the safe methods were exempted from default-deny a miss on a `GET`, `HEAD`
 *   or `OPTIONS` was silent public access rather than a loud `500`;
 * - `req.path` inside a router mounted at a prefix is the path **after** the
 *   prefix (`/ships`, not `/api/ships`), so every key in a table written the
 *   obvious way missed;
 * - and even with the prefix right, the resolver was re-implementing Express's
 *   matcher by hand, so a trailing slash, a case-variant path and a
 *   parameterised route (`/ships/:id`) all missed too.
 *
 * A table lookup cannot be made equivalent to Express's matcher, so this
 * adapter does not try. **Declarations live at registration**, next to the
 * handler, where Express's own matcher binds them:
 *
 * ```ts
 * const api = secured(express.Router());
 * api.get("/ships", auth.requireSession(), listShips);
 * api.post("/ships/:id/navigate", auth.requireScope("fleet:control"), navigate);
 * api.get("/health", auth.allowPublic(), health);
 * app.use("/api/fleet/v1", api);
 * ```
 *
 * Whatever Express matched, it matched the declaration with it. Prefixes,
 * trailing slashes, case, parameters and `app.all` answering an `OPTIONS` are
 * all Express's business and stay Express's business.
 *
 * {@link secured} is the half that cannot be forgotten: it refuses **at
 * registration time** to register a handler that carries no declaration, so
 * the process does not start. An undeclared route cannot exist, rather than
 * being detected once a request finds it.
 *
 * ## The resolver that remains
 *
 * {@link ExpressAuth.guard} survives for routes this package cannot decorate —
 * fleet-service's routes are generated by tsoa, and there is no call site to
 * put a declaration in. Its resolver is **path-independent in practice**: a
 * `use`-mounted middleware runs before any route layer matches, so
 * `req.route` is `undefined` there and no honest path key exists. fleet's
 * resolver is a function of the method alone, which is exactly the shape that
 * is safe.
 *
 * A resolver that returns `undefined`, or throws, means **undeclared**: `500`,
 * on every method, before the header is read. It never falls back to `"none"`.
 *
 * **The guard trusts `req.method`.** Any method-override middleware must be
 * mounted *before* it, or a `POST` arrives here as whatever the override said.
 * This package ignores `X-HTTP-Method-Override` itself and always will.
 */

